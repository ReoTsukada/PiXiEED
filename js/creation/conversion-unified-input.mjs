/** Shared notices stay visible in both views; only the engine-specific surface changes. */
export function conversionRecoveryStatusLabel(state = {}) {
  const phase = state.phase || 'idle';
  const settingsWarning = String(state.message || '').includes('保存停止の設定を再読込後へ引き継げません。');
  if (['error', 'restore-error', 'restore-blocked', 'conflict'].includes(phase) || state.blocked) return '保存エラーを確認';
  if (state.loading || phase === 'loading') return settingsWarning ? '保存確認中・設定注意' : '保存内容を確認中';
  if (state.restoring || phase === 'restoring') return settingsWarning ? '復元中・設定注意' : '復元中';
  if (state.saving || phase === 'saving') return settingsWarning ? '保存中・設定注意' : '保存中';
  if (state.paused || phase === 'paused') {
    if (state.dirty) return settingsWarning ? '未保存・停止設定注意' : '未保存・保存停止中';
    return settingsWarning ? '停止設定に注意' : '自動保存停止中';
  }
  if (state.dirty || phase === 'pending') return settingsWarning ? '保存待ち・設定注意' : '保存待ち';
  if (phase === 'saved') {
    const routine = state.message === '端末内に保存済みです。共有端末ではデータが残ります。'
      || state.message === '端末内の保存版を復元しました。生成結果は必要に応じて作り直します。';
    return routine ? '端末に保存済み' : '保存済み・注意あり';
  }
  return settingsWarning ? '保存設定に注意' : '保存の準備完了';
}
