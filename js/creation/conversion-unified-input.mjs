function extensionOfOutput(value = '') {
  const leaf = String(value || '').split(/[\\/]/).pop();
  const dot = leaf.lastIndexOf('.');
  return (dot > 0 ? leaf.slice(dot + 1) : leaf).toLowerCase();
}

function outputKindFromMetadata({ format = '', filename = '', mimeType = '' } = {}) {
  const mime = String(mimeType || '').split(';', 1)[0].trim().toLowerCase();
  if (mime.startsWith('image/')) return 'image';
  if (mime.startsWith('audio/')) return 'audio';
  if (mime.startsWith('video/')) return 'video';
  if (mime.startsWith('text/') || mime === 'application/json' || mime === 'application/ld+json' || mime.endsWith('+json')) return 'text';
  const extension = extensionOfOutput(format || filename);
  if (IMAGE_OUTPUT_FORMATS.has(extension)) return 'image';
  if (AUDIO_OUTPUT_FORMATS.has(extension)) return 'audio';
  if (VIDEO_OUTPUT_FORMATS.has(extension)) return 'video';
  if (TEXT_OUTPUT_FORMATS.has(extension)) return 'text';
  return extension || mime ? 'file' : 'unknown';
}

/** Classify the saved result, not the input material or the engine that produced it. */
export function classifyConversionOutput({ mode = 'media', source = 'file', action = 'text', renderFormat = 'png', format = '', filename = '', mimeType = '', outputPreview = null, outputReady = false } = {}) {
  if (mode === 'output') {
    const outputFormat = String(format || '').toLowerCase();
    const label = ['ascii', 'block', 'braille', 'emoji', 'custom'].includes(outputFormat) ? '文字アート（TXT）'
      : outputFormat === 'pixels' ? '画素テキスト（TXT）'
        : ['base64', 'dataurl'].includes(outputFormat) ? `${outputFormat === 'base64' ? 'Base64' : 'Data URL'}（TXT）`
          : '復元コード（TXT）';
    return { category: 'text', tab: 'text', format: 'txt', label, mimeType: 'text/plain' };
  }

  if (mode === 'input' && source === 'text' && action === 'text') {
    const selected = String(renderFormat || 'png').toLowerCase();
    if (selected === 'pxtxt') return { category: 'text', tab: 'text', format: 'pxtxt', label: '文章と設定（PXT）', mimeType: 'text/plain' };
    if (selected === 'png' || selected === 'svg') return { category: 'image', tab: 'image', format: selected, label: selected.toUpperCase(), mimeType: selected === 'svg' ? 'image/svg+xml' : 'image/png' };
  }

  const previewMatchesAction = mode === 'input' && source === 'text' && action !== 'text' && outputReady === true
    && outputPreview?.generationMode === mode && outputPreview.action === action && outputPreview.matchesInput === true && outputPreview.kind !== 'unknown';
  const preview = previewMatchesAction ? outputPreview : null;
  const exact = preview?.kind || '';
  // In media mode, the user's selected native format is authoritative. The text engine's
  // retained preview must not relabel it. In restore mode, only current exact metadata counts.
  const metadata = outputKindFromMetadata({
    format: preview?.format || (mode === 'media' ? format : ''),
    filename: preview?.filename || '',
    mimeType: preview?.mimeType || '',
  });
  // A supported MIME is the strongest description of the generated bytes. It
  // can correct either a misleading extension or stale/inconsistent kind data.
  const previewMimeKind = preview ? outputKindFromMetadata({ mimeType: preview.mimeType }) : 'unknown';
  const category = previewMimeKind !== 'unknown' ? previewMimeKind
    : exact === 'text' || exact === 'image' ? exact
      : metadata !== 'unknown' ? metadata : exact === 'file' ? 'file' : 'unknown';
  const tab = category === 'text' ? 'text' : 'image';
  const selectedFormat = preview?.format || (mode === 'media' ? format : '');
  const label = category === 'image' ? (selectedFormat ? selectedFormat.toUpperCase() : '画像')
    : category === 'audio' ? '音声ファイル'
      : category === 'video' ? '動画ファイル'
        : category === 'text' ? (selectedFormat === 'pxtxt' ? '文章と設定（PXT）' : selectedFormat ? `${selectedFormat.toUpperCase()}（テキスト）` : 'テキスト')
          : 'ファイル';
  const inferredMime = category === 'image' ? (selectedFormat === 'svg' ? 'image/svg+xml' : selectedFormat === 'png' ? 'image/png' : 'image/*')
    : category === 'audio' ? 'audio/*' : category === 'video' ? 'video/*' : category === 'text' ? 'text/plain' : '';
  return { category, tab, format: selectedFormat, label, mimeType: preview ? (preview.mimeType || inferredMime) : mode === 'media' ? inferredMime : '' };
}

/** Resolve only the current material's exact original File; never borrow snapshot.file after selection changes. */
export function activeConversionSourceFile({ stateFile = null, materialState = null, getOriginalFileForAsset = () => null } = {}) {
  if (!materialState?.loaded) return stateFile || null;
  const assets = Array.isArray(materialState.assets) ? materialState.assets : [];
  const active = materialState.activeId
    ? assets.find(asset => asset?.id === materialState.activeId)
    : assets[0];
  if (!active) return null;
  return active.originalFile || active.file || active.sourceFile || getOriginalFileForAsset(active.id, active) || null;
}

/** In output mode the selected File is authoritative; media mode follows the active native asset. */
export function resolveConversionSourceFile({ sourceKind = 'file', mode = 'media', stateFile = null, explicitOriginalFile = null, materialState = null, getOriginalFileForAsset = () => null } = {}) {
  if (sourceKind === 'file' && mode === 'output') return explicitOriginalFile && stateFile === explicitOriginalFile ? explicitOriginalFile : stateFile || null;
  return activeConversionSourceFile({ stateFile, materialState, getOriginalFileForAsset });
}

/** Associate committed Files only when they correspond to the full replacement or exact appended asset slice. */
export function associateCommittedMaterialFiles({ assets = [], files = [], previousAssetIds = [] } = {}) {
  const current = Array.isArray(assets) ? assets : [];
  const committed = Array.from(files || []);
  const previous = new Set(previousAssetIds || []);
  const added = current.filter(asset => asset?.id && !previous.has(asset.id));
  const firstSingleGroupedSource = previous.size === 0 && current.length === 1 && committed.length === 1
    && /^local-(images|audio|video)$/.test(String(current[0]?.id || ''));
  if (firstSingleGroupedSource) return { associations: [[current[0].id, committed[0]]], assetIds: current.map(asset => asset.id), invalidatedIds: [] };

  const targets = current.length === committed.length ? current : added.length === committed.length ? added : [];
  if (!committed.length || targets.length !== committed.length || targets.some(asset => !/^material-\d+-/.test(String(asset.id || '')))) {
    const invalidatedIds = current.filter(asset => /^local-(images|audio|video)$/.test(String(asset?.id || '')) && previous.has(asset.id)).map(asset => asset.id);
    return { associations: [], assetIds: current.map(asset => asset?.id).filter(Boolean), invalidatedIds };
  }
  // conversion-timeline preserves selected file order when creating/replacing
  // assets, and appends each successfully loaded addition in that same order.
  return { associations: targets.map((asset, index) => [asset.id, committed[index]]), assetIds: current.map(asset => asset.id), invalidatedIds: [] };
}

/** Return a native asset only when its original File identity is known exactly. */
export function activeConversionAssetIdForFile(file, materialState = null, getAssetIdForOriginalFile = () => null) {
  if (!file || !materialState?.loaded) return null;
  const assets = Array.isArray(materialState.assets) ? materialState.assets : [];
  const direct = assets.find(asset => asset && (asset.originalFile === file || asset.file === file || asset.sourceFile === file));
  if (direct) return direct.id || null;
  return getAssetIdForOriginalFile(file, materialState) || null;
}

/** Select the exact matching native asset before re-entering media mode. */
export async function selectConversionNativeMaterialForFile({ file, materialState = null, getAssetIdForOriginalFile = () => null, selectAsset = () => false } = {}) {
  if (!materialState?.loaded) return true;
  const assetId = activeConversionAssetIdForFile(file, materialState, getAssetIdForOriginalFile);
  if (!assetId) return false;
  if (materialState.activeId === assetId) return true;
  return (await selectAsset(assetId)) === true;
}

/** Resolve a tab click into a route for the same active source, or explain why it is unavailable. */
export function planConversionOutputTabRoute({ tab, source = 'file', mode = 'media', action = 'text', currentTab = 'image', fileKind = 'unknown', hasSource = false, hasOriginalFile = false, hasNativeAsset = false, mediaLoaded = false, imageFormat = 'png' } = {}) {
  if (!OUTPUT_TABS.includes(tab)) return { available: false, reason: 'この出力形式は選べません。' };
  if (tab === currentTab) return { available: true, route: 'keep' };

  if (source === 'text') {
    if (action !== 'text') return { available: false, reason: '現在の復元方法と入力は保持しています。「別の用途」から文章を画像にする操作を選んでください。' };
    return tab === 'image'
      ? { available: true, route: 'text-image', renderFormat: ['png', 'svg'].includes(imageFormat) ? imageFormat : 'png' }
      : { available: true, route: 'text-project', renderFormat: 'pxtxt' };
  }

  if (source !== 'file' || !hasSource) return { available: false, reason: '同じ素材で選べる出力がありません。素材を選んでください。' };
  if (tab === 'text') {
    return fileKind === 'image' && hasOriginalFile
      ? { available: true, route: 'file-art' }
      : { available: false, reason: fileKind === 'image'
        ? '選択中の画像の元ファイルを特定できないため、別の画像には切り替えません。元ファイルを選び直すと文字アートにできます。'
        : '文字アート（TXT）は画像素材に対応します。復元コードは「別の用途」から選べます。' };
  }
  if (mode === 'media') return { available: true, route: 'keep' };
  return hasOriginalFile && (!mediaLoaded || hasNativeAsset) && (['image', 'media', 'audio', 'video'].includes(fileKind) || (fileKind === 'binary' && mediaLoaded))
    ? { available: true, route: 'file-media' }
    : { available: false, reason: !hasOriginalFile ? '選択中の素材の元ファイルを特定できないため、別の素材には切り替えません。元ファイルを選び直してください。'
      : mediaLoaded && !hasNativeAsset ? 'この元ファイルと素材欄の選択を照合できないため、別の素材には切り替えません。素材欄で同じ元ファイルを選び直してください。'
        : 'この素材を画像・音声・動画として出力できません。入力と設定は保持しています。' };
}

/** Tabs track the classified output. Route transitions are performed separately and never infer a source. */
export function createConversionOutputTabController({ getTab = () => 'image', isBusy = () => false, isComposing = () => false } = {}) {
  let selected = OUTPUT_TABS.includes(getTab()) ? getTab() : 'image';
  return {
    observe(nextTab = getTab()) {
      if (OUTPUT_TABS.includes(nextTab)) selected = nextTab;
      return { tab: selected };
    },
    select(nextTab, { busy = false, composing = false, available = true } = {}) {
      if (!OUTPUT_TABS.includes(nextTab)) return false;
      if (busy || composing || isBusy() || isComposing()) return false;
      if (!available) return false;
      selected = nextTab;
      return true;
    },
    snapshot() { return { tab: selected }; },
  };
}

