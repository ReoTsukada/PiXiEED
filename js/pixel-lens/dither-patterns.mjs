function pattern(id, label, group, cell, tiles) {
  const levels = tiles.map((rows) => {
    const bits = new Uint8Array(64);
    rows.forEach((row, y) => { for (let x = 0; x < 8; x++) bits[y * 8 + x] = row[x] === '#' ? 1 : 0; });
    return bits;
  });
  const coverage = [0, ...levels.map((bits) => bits.reduce((sum, bit) => sum + bit, 0) / 64), 1];
  const all = [new Uint8Array(64), ...levels, new Uint8Array(64).fill(1)];
  // tone (0..255, share of the lighter colour) → the step whose coverage is closest
  const levelForTone = new Uint8Array(256);
  for (let v = 0; v < 256; v++) {
    const f = v / 255; let best = 0;
    for (let k = 1; k < coverage.length; k++) if (Math.abs(coverage[k] - f) < Math.abs(coverage[best] - f)) best = k;
    levelForTone[v] = best;
  }
  return Object.freeze({ id, label, group, cell, tiles: Object.freeze(tiles), levels: Object.freeze(all), coverage: Object.freeze(coverage), levelForTone });
}
