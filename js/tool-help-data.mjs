function normalizePathname(pathname) {
  let path = String(pathname ?? '').trim() || '/';
  path = path.split(/[?#]/, 1)[0] || '/';
  path = path.replace(/\/index\.html$/i, '/');
  if (path !== '/' && !path.endsWith('/') && !/\.[a-z0-9]+$/i.test(path)) path += '/';
  return path;
}

/** Return the guide for a known route, or null for routes without tool help. */
export function getToolGuide({ pathname = '', search = '' } = {}) {
  const rawPath = String(pathname ?? '');
  const path = normalizePathname(rawPath);
  if (path === '/globe-prototype.html') {
    const embeddedSearch = rawPath.match(/[?]([^#]*)/)?.[1] ?? '';
    const explicitSearch = String(search).replace(/^\?/, '');
    const params = new URLSearchParams([embeddedSearch, explicitSearch].filter(Boolean).join('&'));
    const toolValues = params.getAll('tool');
    return toolValues.length === 1 && toolValues[0] === 'telescope' ? guideById.get('telescope') : null;
  }
  const id = guideByPath.get(path);
  return id ? guideById.get(id) : null;
}
