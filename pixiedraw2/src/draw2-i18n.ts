const JA_TO_EN: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(EN_TO_JA).map(([english, japanese]) => [japanese, english]),
);

type TranslationPair = readonly [string, string];

// Translation is used by editor render paths, so do not sort the complete
// dictionary for every generated Timeline label. Keep this cache bounded:
// user-provided names must never be allowed to grow it without limit.
const SORTED_EN_TO_JA: readonly TranslationPair[] = Object.entries(EN_TO_JA)
  .sort(([left], [right]) => right.length - left.length);
const SORTED_JA_TO_EN: readonly TranslationPair[] = Object.entries(JA_TO_EN)
  .sort(([left], [right]) => right.length - left.length);
const TRANSLATION_CACHE_LIMIT = 512;
const translationCache = new Map<string, string>();

export function normalizeDraw2Locale(value: unknown): Draw2Locale {
  return value === "ja" ? "ja" : "en";
}

export function translateDraw2Text(text: string, locale: Draw2Locale): string {
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const core = text.slice(
    leading.length,
    text.length - trailing.length || undefined,
  );
  if (core.length === 0) return text;
  const cacheKey = `${locale}\u0000${core}`;
  const cached = translationCache.get(cacheKey);
  if (cached !== undefined) return `${leading}${cached}${trailing}`;
  const table = locale === "ja" ? EN_TO_JA : JA_TO_EN;
  const sortedTable = locale === "ja" ? SORTED_EN_TO_JA : SORTED_JA_TO_EN;
  const exact = table[core];
  const translated = exact ?? sortedTable
    .reduce(
      (value, [source, target]) => value.split(source).join(target),
      core,
    );
  if (translationCache.size >= TRANSLATION_CACHE_LIMIT) {
    const firstKey = translationCache.keys().next().value;
    if (typeof firstKey === "string") translationCache.delete(firstKey);
  }
  translationCache.set(cacheKey, translated);
  return `${leading}${translated}${trailing}`;
}

export function draw2LocaleLabel(locale: Draw2Locale): string {
  return locale === "ja" ? "日本語" : "English";
}
