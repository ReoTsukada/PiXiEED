#!/usr/bin/env node
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const exists = (path) => existsSync(new URL(path, root));

const clientFiles = [
  'pixiedraw2/src/fp003-financial-bundle-entry.ts',
  'pixiedraw2/src/wp210-market-bundle-entry.ts',
  'pixiedraw2/src/wp220-direct-work-bundle-entry.ts',
  'pixiedraw2/src/fp003y-client-contract.ts',
];
const serverOnlyImports = [
  'src/server/',
  'authority-composition-root',
  'authority-composition-internal',
  'canonical-registry-adapter',
  'resolveFinancial',
  'service-role',
  'providerCredential',
];
for (const file of clientFiles) {
  const source = read(file);
  for (const token of serverOnlyImports) assert.equal(source.includes(token), false, `${file} contains server-only token ${token}`);
}
const allBrowserEntries = readdirSync(new URL('pixiedraw2/src/', root)).filter((file) => file.endsWith('bundle-entry.ts')).map((file) => `pixiedraw2/src/${file}`);
for (const file of allBrowserEntries) {
  const source = read(file);
  for (const token of serverOnlyImports) assert.equal(source.includes(token), false, `${file} contains server-only token ${token}`);
}

assert.equal(exists('pixiedraw2/src/fp003x-cross-layer-authority.ts'), false, 'The old Provider-injectable source entry must be removed.');
assert.equal(exists('pixiedraw2/src/fp003y-server-authority-runtime.ts'), false, 'The old runtime entry must be removed.');
const runtime = read('pixiedraw2/src/server/authority-composition-root.ts');
assert.match(runtime, /export const fp003zHandler = defaultComposition\.handler/u, 'Server root must export only the fixed authenticated Handler.');
assert.doesNotMatch(runtime, /export const fp003zService/u, 'Server root must not expose the domain Service bypass.');
assert.doesNotMatch(runtime, /create\w*Service\([^)]*provider/u, 'Server release root must not expose a Provider-accepting factory.');
assert.doesNotMatch(runtime, /export function\s+create.*Registry/u, 'Server release root must not expose a Registry factory.');
const internal = read('pixiedraw2/src/server/authority-composition-internal.ts');
assert.match(internal, /composeAuthorityService\s*\(\s*registry:\s*CanonicalRegistryAdapter\s*,?\s*\)/u, 'Server composition must depend on a Registry adapter, not a Provider.');

const distFiles = readdirSync(new URL('pixiedraw2/dist/', root))
  .filter((file) => /\.(?:js|mjs)$/u.test(file))
  .map((file) => `pixiedraw2/dist/${file}`)
  .sort();
const staleDistTokens = ['src/wp220-direct-work-core.ts', 'src/wp210-market-rights-core.ts', 'createInternalFp003XService', 'SERVER_AUTHORITY_UNAVAILABLE', 'createDirectWorkLedgerEntryFromServerCanonical'];
for (const file of distFiles) {
  assert.equal(exists(file), true, `${file} must be generated by the safe Browser entry.`);
  const dist = read(file);
  for (const token of staleDistTokens) assert.equal(dist.includes(token), false, `${file} contains stale/server token ${token}`);
}
const denoConfig = JSON.parse(read('pixiedraw2/deno.json'));
const buildGraph = [
  ['build:market', 'src/wp210-market-bundle-entry.ts', 'dist/wp210-market-core.js'],
  ['build:market:min', 'src/wp210-market-bundle-entry.ts', 'dist/wp210-market-core.min.js'],
  ['build:direct-work', 'src/wp220-direct-work-bundle-entry.ts', 'dist/wp220-direct-work-core.js'],
  ['build:direct-work:min', 'src/wp220-direct-work-bundle-entry.ts', 'dist/wp220-direct-work-core.min.js'],
  ['build:fp003', 'src/fp003-financial-bundle-entry.ts', 'dist/fp003-financial-integrity-core.js'],
  ['build:fp003:min', 'src/fp003-financial-bundle-entry.ts', 'dist/fp003-financial-integrity-core.min.js'],
];
for (const [task, entry, output] of buildGraph) {
  assert.equal(typeof denoConfig.tasks?.[task], 'string', `${task} must remain in the build graph.`);
  assert.match(denoConfig.tasks[task], new RegExp(entry.replaceAll('/', '\\/')), `${task} must build from ${entry}.`);
  assert.match(denoConfig.tasks[task], new RegExp(output.replaceAll('/', '\\/')), `${task} must generate ${output}.`);
}

const sns = read('pixiedraw2/src/wp230-sns-community-core.ts');
const wp240 = read('pixiedraw2/src/wp240-admin-analytics-ads-core.ts');
const wp250 = read('pixiedraw2/src/wp250-policy-economics-core.ts');
const authorityFindings = [
  [sns, /input\.authorizationProof\?\.principalId/u, 'SNS caller Proof Principal fallback'],
  [wp240, /principalId:\s*input\.authorizationProof\?\.principalId/u, 'WP-240 caller Proof Principal fallback'],
  [wp250, /principalId:\s*input\.authorizationProof\?\.principalId/u, 'WP-250 caller Proof Principal fallback'],
  [wp250, /principalId:\s*input\.actorReference/u, 'WP-250 caller actor as Proof expectation'],
];
for (const [source, pattern, label] of authorityFindings) assert.equal(pattern.test(source), false, `${label} remains a Security Authority fallback.`);
assert.match(wp250, /actorReference:\s*authorizationProof\?\.principalId/u, 'Admin audit output must use the canonical server actor.');

console.log(JSON.stringify({
  browserEntriesChecked: allBrowserEntries.length,
  serverOnlyCompositionRoot: 'fixed-instance-only',
  releaseProviderInjection: 0,
  staleDistArtifacts: 0,
  buildGraph: buildGraph.map(([task, entry, output]) => ({ task, entry, output })),
  securityAuthorityFallbacks: 0,
  policyOnlyAndShadowFields: 'not treated as AuthorizationProof',
}, null, 2));
