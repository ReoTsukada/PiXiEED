#!/usr/bin/env node
/** Build a deterministic 0.5-degree world land mask from Natural Earth GeoJSON. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'assets/maps/world-countries-110m.geojson');
const outputPath = path.join(root, 'assets/maps/world-land-mask-v1.mjs');
const WIDTH = 720;
const HEIGHT = 360;

function normalizeLongitude(value) { return ((value + 180) % 360 + 360) % 360 - 180; }
function boundsOfGeometry(geometry) {
  const points = [];
  const visit = (value) => {
    if (Array.isArray(value) && value.length >= 2 && typeof value[0] === 'number') points.push(value);
    else if (Array.isArray(value)) value.forEach(visit);
  };
  visit(geometry.coordinates);
  if (!points.length) return null;
  const xs = points.map((point) => normalizeLongitude(point[0]));
  return { west: Math.min(...xs), east: Math.max(...xs), south: Math.min(...points.map((point) => point[1])), north: Math.max(...points.map((point) => point[1])) };
}
function pointInRing(point, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0]; const yi = ring[i][1]; const xj = ring[j][0]; const yj = ring[j][1];
    const intersects = ((yi > point[1]) !== (yj > point[1])) && (point[0] < ((xj - xi) * (point[1] - yi)) / (yj - yi) + xi);
    if (intersects) inside = !inside;
  }
  return inside;
}
function pointInPolygon(point, polygon) { return pointInRing(point, polygon[0]) && !polygon.slice(1).some((ring) => pointInRing(point, ring)); }
function pointInGeometry(point, geometry) {
  if (!geometry) return false;
  if (geometry.type === 'Polygon') return pointInPolygon(point, geometry.coordinates);
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.some((polygon) => pointInPolygon(point, polygon));
  return false;
}
function landAt(longitude, latitude, geometries) {
  const point = [longitude, latitude];
  return geometries.some(({ geometry, bounds }) => {
    if (latitude < bounds.south || latitude > bounds.north) return false;
    if (bounds.west <= bounds.east && (longitude < bounds.west || longitude > bounds.east)) return false;
    return pointInGeometry(point, geometry);
  });
}
function encodeRle(values) {
  const runs = [];
  let start = 0;
  while (start < values.length) {
    const value = values[start];
    let end = start + 1;
    while (end < values.length && values[end] === value) end += 1;
    runs.push([value, end - start]);
    start = end;
  }
  return runs;
}
function checksum(values) {
  let hash = 2166136261;
  for (const value of values) { hash ^= value; hash = Math.imul(hash, 16777619); }
  return `fnv1a32-${(hash >>> 0).toString(16).padStart(8, '0')}`;
}

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const geometries = source.features.map((feature) => ({ geometry: feature.geometry, bounds: boundsOfGeometry(feature.geometry) })).filter((entry) => entry.bounds);
const values = new Uint8Array(WIDTH * HEIGHT);
for (let row = 0; row < HEIGHT; row += 1) {
  const latitude = 90 - (row + 0.5) * 0.5;
  for (let column = 0; column < WIDTH; column += 1) {
    const longitude = -180 + (column + 0.5) * 0.5;
    values[row * WIDTH + column] = landAt(longitude, latitude, geometries) ? 255 : 0;
  }
}
const runs = encodeRle(values);
const body = `/** Generated by scripts/build-globe-land-mask.mjs. Do not edit manually. */\nexport const WORLD_LAND_MASK = Object.freeze(${JSON.stringify({ version: 'world-land-mask-v1', width: WIDTH, height: HEIGHT, cellDegrees: 0.5, source: 'world-countries-110m.geojson', checksum: checksum(values), runs })});\n`;
fs.writeFileSync(outputPath, body);
console.log(JSON.stringify({ outputPath, width: WIDTH, height: HEIGHT, runs: runs.length, bytes: Buffer.byteLength(body) }));
