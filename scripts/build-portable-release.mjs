#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildPagesSite } from './build-pages-site.mjs';

const sourceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const markerName = '.pixieed-generated-puzzle-share-pages';
const markerContents = 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n';

function run(command, args, options = {}) {
  return execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...options });
}

async function assertReusablePuzzlePages(root) {
  for (const game of ['spot-difference', 'hidden-object']) {
    const directory = join(root, 'play', game, 'puzzles');
    const info = await lstat(directory).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (!info || !info.isDirectory() || info.isSymbolicLink()) throw new Error(`Missing generated puzzle directory: play/${game}/puzzles`);
    if (await readFile(join(directory, markerName), 'utf8').catch(() => '') !== markerContents) throw new Error(`Unrecognized generated puzzle directory: play/${game}/puzzles`);
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.name === markerName) continue;
      if (!entry.isDirectory()) throw new Error(`Unexpected generated puzzle entry: play/${game}/puzzles/${entry.name}`);
      const children = await readdir(join(directory, entry.name), { withFileTypes: true });
      if (!children.some(child => child.isFile() && child.name === 'index.html')) throw new Error(`Puzzle page is missing: play/${game}/puzzles/${entry.name}`);
      if (!children.some(child => child.isFile() && /^ogp-[a-f0-9]{16}\.png$/.test(child.name))) throw new Error(`Puzzle OGP image is missing: play/${game}/puzzles/${entry.name}`);
    }
  }
}

async function hashFile(path) {
  return createHash('sha256').update(await readFile(path)).digest('hex');
}

async function listManifestFiles(directory, prefix = '') {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await listManifestFiles(path, relative));
    else if (entry.isFile()) result.push({ path: relative, sha256: await hashFile(path) });
    else throw new Error(`Unexpected non-file in site artifact: ${relative}`);
  }
  return result.sort((a, b) => a.path.localeCompare(b.path));
}

/** Build a portable ZIP from the existing Pages artifact builder without publishing it. */
export async function buildPortableRelease({ root = sourceRoot, output, reusePuzzles = false } = {}) {
  root = await realpath(resolve(root));
  if (typeof output !== 'string' || !output) throw new Error('An explicit output directory is required');
  const requested = resolve(output);
  const parent = await realpath(dirname(requested));
  const destination = join(parent, basename(requested));
  if (destination === root || destination.startsWith(`${root}${sep}`) || root.startsWith(`${destination}${sep}`)) {
    throw new Error('Output must be outside and must not contain the source repository');
  }
  try { await lstat(destination); throw new Error('Output directory already exists; refusing to overwrite it'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }

  let created = false;
  try {
    await mkdir(destination, { recursive: false });
    created = true;
    if (reusePuzzles) await assertReusablePuzzlePages(root);
    else run(process.execPath, [join(root, 'scripts/generate-puzzle-ogp-pages.mjs'), '--generate'], { cwd: root, env: process.env });

    const site = join(destination, 'site');
    const built = await buildPagesSite({ root, output: site });
    const files = await listManifestFiles(site);
    const zipPath = join(destination, 'site.zip');
    run('zip', ['-q', '-r', zipPath, '.'], { cwd: site });
    const revision = run('git', ['rev-parse', 'HEAD'], { cwd: root }).trim();
    const trackedDirty = Boolean(run('git', ['status', '--porcelain', '--untracked-files=no'], { cwd: root }).trim());
    const manifest = {
      generatedAt: new Date().toISOString(),
      gitRevision: revision,
      trackedDirty,
      puzzleMode: reusePuzzles ? 'reuse' : 'refresh',
      puzzleModeNote: reusePuzzles ? 'Reuses saved public puzzle data; new posts and withdrawals may not be reflected.' : 'Refreshed from current public puzzle data before packaging.',
      puzzlePages: built.puzzlePages,
      fileCount: files.length,
      zipSha256: await hashFile(zipPath),
      files,
    };
    await writeFile(join(destination, 'release.json'), `${JSON.stringify(manifest, null, 2)}\n`, { flag: 'wx' });
    return { output: destination, zip: zipPath, manifest: join(destination, 'release.json'), fileCount: files.length, puzzlePages: built.puzzlePages, puzzleMode: manifest.puzzleMode };
  } catch (error) {
    if (created) await rm(destination, { recursive: true, force: true });
    throw error;
  }
}

function parseArgs(args) {
  let output;
  let reusePuzzles = false;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--output' && args[i + 1] && !output) output = args[++i];
    else if (args[i] === '--reuse-puzzles' && !reusePuzzles) reusePuzzles = true;
    else throw new Error('Usage: node scripts/build-portable-release.mjs --output <new directory> [--reuse-puzzles]\n--reuse-puzzles uses saved public data and may omit new posts or withdrawals; refresh is the default.');
  }
  if (!output) throw new Error('Usage: node scripts/build-portable-release.mjs --output <new directory> [--reuse-puzzles]\n--reuse-puzzles uses saved public data and may omit new posts or withdrawals; refresh is the default.');
  return { output, reusePuzzles };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await buildPortableRelease(parseArgs(process.argv.slice(2)))));
}
