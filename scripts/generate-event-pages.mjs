async function hasGeneratedOutput(outputDir) {
  try {
    const state = await lstat(outputDir);
    if (!state.isDirectory() || state.isSymbolicLink()) throw new Error('Events output path is not a regular directory.');
    const marker = await readFile(resolve(outputDir, markerName), 'utf8').catch(() => '');
    if (marker !== markerContents) throw new Error('Events directory is not generated by this script; refusing to replace it.');
    return true;
  } catch (error) { if (error?.code === 'ENOENT') return false; throw error; }
}

async function writePagesTo(root, events, allRecords = events) {
  const outputDir = resolve(root, 'events');
  const token = `${process.pid}-${randomUUID()}`;
  const stage = `${outputDir}.stage-${token}`;
  const backup = `${outputDir}.backup-${token}`;
  let movedOld = false;
  try {
    await mkdir(stage);
    await writeFile(resolve(stage, markerName), markerContents, { flag: 'wx' });
    await writeFile(resolve(stage, 'index.html'), indexPage(events, allRecords), { flag: 'wx' });
    const manifest = { version: 1, ids: events.map((event) => event.id) };
    await writeFile(resolve(stage, 'catalog.json'), `${JSON.stringify(manifest, null, 2)}\n`, { flag: 'wx' });
    const indexableIds = new Set(events.map((event) => event.id));
    for (const event of events) {
      const directory = resolve(stage, event.id);
      await mkdir(directory);
      await writeFile(resolve(directory, 'index.html'), eventPage(event, allRecords, indexableIds), { flag: 'wx' });
    }
    if (await hasGeneratedOutput(outputDir)) { await rename(outputDir, backup); movedOld = true; }
    try { await rename(stage, outputDir); }
    catch (error) { if (movedOld) { await rename(backup, outputDir); movedOld = false; } throw error; }
    if (movedOld) await rm(backup, { recursive: true, force: true });
  } finally { await rm(stage, { recursive: true, force: true }); }
}

async function updateSitemap(root, ids) {
  const sitemapPath = resolve(root, 'sitemap.xml');
  let sitemap;
  try {
    const state = await lstat(sitemapPath);
    if (!state.isFile() || state.isSymbolicLink()) throw new Error('sitemap.xml must be a regular file.');
    sitemap = await readFile(sitemapPath, 'utf8');
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
    sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</urlset>\n';
  }
  if (!/<urlset\b[^>]*>[\s\S]*<\/urlset>/.test(sitemap)) throw new Error('sitemap.xml has no valid urlset root.');
  const blocks = [...sitemap.matchAll(/<url\b[^>]*>\s*<loc>([\s\S]*?)<\/loc>[\s\S]*?<\/url>/g)];
  const keptBlocks = blocks.map((match) => ({ block: match[0].trim(), url: match[1].trim() }))
    .filter(({ url }) => !/^https:\/\/pixieed\.jp\/events(?:\/|$)/.test(url))
    .map(({ block }) => block);
  const routes = ['/events/', ...ids.map((id) => `/events/${id}/`)];
  const urlEntries = routes.map((route) => `<url><loc>${origin}${route}</loc></url>`);
  const allEntries = [...keptBlocks, ...urlEntries];
  const first = blocks[0];
  const last = blocks.at(-1);
  const closeAt = sitemap.lastIndexOf('</urlset>');
  const prefix = first ? sitemap.slice(0, first.index).trimEnd() : sitemap.slice(0, closeAt).trimEnd();
  const suffix = last ? sitemap.slice(last.index + last[0].length, closeAt).trim() : '';
  const ending = sitemap.slice(closeAt).trim();
  const normalized = `${prefix}\n${allEntries.map((entry) => `  ${entry}`).join('\n')}${suffix ? `\n${suffix}` : ''}\n${ending}\n`;
  await writeFile(sitemapPath, normalized, 'utf8');
}

async function generateEventPages({ root = sourceRoot } = {}) {
  const resolvedRoot = resolve(root);
  const catalog = JSON.parse(await readFile(resolve(resolvedRoot, 'data/pixel-art-events.json'), 'utf8'));
  const events = eligibleEvents(catalog);
  await writePagesTo(resolvedRoot, events, catalog.events);
  await updateSitemap(resolvedRoot, events.map((event) => event.id));
  const files = ['events/index.html', 'events/catalog.json', ...events.map((event) => `events/${event.id}/index.html`), 'sitemap.xml'];
  return { eventPages: events.length, files, ids: events.map((event) => event.id) };
}

