function display(value) { return typeof value === 'string' && value.trim() ? value.trim() : '未確認'; }
function displayPeople(value) {
  if (Array.isArray(value)) return value.map((person) => typeof person === 'string' ? person : person?.name).filter(Boolean).join('・') || '未確認';
  return display(value);
}
function eventStatus(event, today = tokyoDate(), now = Date.now()) {
  if (event.status === 'ended') return 'ended';
  // A registration cutoff can precede the event itself. Keep the event's
  // public state tied to its actual dates and expose the cutoff separately.
  const period = classifyEvent({ ...event, deadlineAt: undefined }, today, now);
  if (period === 'past') return 'ended';
  if (period === 'active') return 'active';
  if (period === 'upcoming') return 'upcoming';
  if (period === 'watch' || period === 'cancelled' || period === 'postponed') return period;
  return event.status || 'unknown';
}
function statusLabel(event) { return statusLabels[eventStatus(event)] || statusLabels.unknown; }
function registrationDeadline(event) {
  const timestamp = Date.parse(event?.deadlineAt || '');
  if (!Number.isFinite(timestamp)) return '';
  return new Intl.DateTimeFormat('ja-JP', {
    timeZone: 'Asia/Tokyo', year: 'numeric', month: 'long', day: 'numeric',
    hour: '2-digit', minute: '2-digit', hourCycle: 'h23',
  }).format(timestamp);
}
function historyForWatch(watch, records) {
  const key = String(watch.name || '').normalize('NFKC').trim().toLocaleLowerCase();
  const prefix = watch.id.replace(/-watch$/, '');
  return records.filter((candidate) => candidate.id !== watch.id && candidate.status !== 'watch'
    && (candidate.id.startsWith(`${prefix}-`) || String(candidate.name || '').normalize('NFKC').trim().toLocaleLowerCase() === key));
}

function eligibleEvents(catalog) {
  if (catalog?.version !== 1 || !Array.isArray(catalog.events)) throw new Error('Event catalog version or events is invalid.');
  const seen = new Set();
  const eligible = catalog.events.filter((event) => {
    if (!event || typeof event.id !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(event.id) || seen.has(event.id)) throw new Error('Event IDs must be unique lowercase URL slugs.');
    seen.add(event.id);
    if (HUB_ONLY_REASONS[event.id]) return false;
    // An indexable page needs an accountable source and checked date, a confirmed
    // event date, and a substantive event-specific description.
    if (!safeUrl(event.sourceUrl) || !event.checkedAt) return false;
    if (event.status === 'watch') return false;
    return Boolean(event.startDate || event.endDate || event.dateLabel) && Boolean(event.description?.trim());
  });
  return uniqueEventEditions(eligible);
}

function eventFacts(event) {
  const date = event.status === 'watch'
    ? (event.dateLabel || `次回開催情報待ち。前回開催日：${display(event.lastHeldDate)}`)
    : (event.dateLabel || (event.startDate && event.endDate ? `${event.startDate}${event.endDate !== event.startDate ? ` 〜 ${event.endDate}` : ''}` : '未確認'));
  const location = [event.prefecture, event.area, event.venue].filter((value) => typeof value === 'string' && value.trim()).join('・') || '未確認';
  return [
    ['正式名称', display(event.officialName)],
    ['掲載名', display(event.name)],
    ['通称', display(event.nickname)],
    ['開催回', display(event.edition)],
    ['開催日時', date],
    ...(registrationDeadline(event) ? [['申込・応募締切', registrationDeadline(event)]] : []),
    ['会場', location],
    ['参加方法', display(event.participation)],
    ['主催', displayPeople(event.organizer)],
    ['開催状態', statusLabel(event)],
    ['情報確認日', display(event.checkedAt)],
    ['情報源', display(event.sourceLabel)],
  ];
}

function relatedSeries(event, allEvents) {
  const normalizedName = String(event.name || '').normalize('NFKC').trim().toLocaleLowerCase();
  return allEvents.filter((candidate) => candidate.status === 'watch'
    && (event.id.startsWith(`${candidate.id.replace(/-watch$/, '')}-`) || String(candidate.name || '').normalize('NFKC').trim().toLocaleLowerCase() === normalizedName));
}

function eventYear(event) {
  const date = event.startDate || event.endDate || event.lastHeldDate || event.dateLabel || '';
  return String(date).match(/(?:19|20)\d{2}/)?.[0] || '';
}

function eventRegion(event) {
  return [event.country, event.prefecture, event.region, event.area]
    .find((value) => typeof value === 'string' && value.trim())?.trim()
    || (event.online === true ? 'オンライン' : '地域未確認');
}

function eventFormat(event) {
  if (event.online === true) return 'online';
  if (event.online === false) return 'in-person';
  return 'unknown';
}

function metaDescription(event, summary) {
  const date = event.startDate
    ? `${event.startDate}${event.endDate && event.endDate !== event.startDate ? `〜${event.endDate}` : ''}`
    : (event.dateLabel || '');
  const location = event.venue || event.area || event.prefecture || '';
  const datePart = date ? `開催日: ${date}` : '';
  const locationLabel = location ? `会場: ${location}` : '';
  const state = eventStatus(event);
  const stateLabel = ['ended', 'cancelled', 'postponed'].includes(state) ? `状態: ${statusLabels[state]}` : '';
  const fixedSuffixLength = Array.from(datePart).length + Array.from(stateLabel).length + (datePart && stateLabel ? 1 : 0) + 2;
  const maxLocationLength = Math.max(0, 95 - fixedSuffixLength - (locationLabel ? 1 : 0));
  const fittedLocation = locationLabel ? Array.from(locationLabel).slice(0, maxLocationLength).join('') : '';
  const suffixParts = [datePart, fittedLocation, stateLabel].filter(Boolean);
  const suffix = suffixParts.length
    ? `（${suffixParts.join('・')}）`
    : '';
  const summaryBudget = Math.max(0, 155 - Array.from(suffix).length);
  return `${Array.from(summary).slice(0, summaryBudget).join('').trimEnd()}${suffix}`;
}

function detailPageTitle(event) {
  const year = eventYear(event);
  const yearContext = year && !new RegExp(`(?:^|\\D)${year}(?:\\D|$)`).test(event.name) ? `${year}年` : '';
  const location = event.online === true
    ? 'オンライン'
    : (event.prefecture || event.area || event.region || event.country || '');
  const context = [yearContext, location].filter(Boolean).join('・');
  return `${event.name}${context ? `｜${context}` : ''}｜ドット絵イベント情報｜PiXiEED`;
}

