#!/usr/bin/env node
/**
 * Generates crawler-readable puzzle share pages (OGP) from the public post reader,
 * one set per game: play/spot-difference/puzzles/<id>/ and play/hidden-object/puzzles/<id>/.
 * The ID-specific static-page pattern is based on d93b55ff:scripts/generate-puzzle-ogp-pages.mjs.
 * No output is written without an explicit --generate argument.
 */
import { lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { supabaseConfig } from '../data/site-config.js';
import { createPuzzleSharePage } from '../js/creation/puzzle-share-page.mjs';
import { buildPuzzleShareArtifacts } from './lib/puzzle-ogp-artifacts.mjs';
import { createHiddenObjectOgpRenderer } from './lib/puzzle-ogp-browser.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GAMES = Object.freeze({ spot_difference: 'spot-difference', hidden_object: 'hidden-object' });
const outputDirFor = (mode) => resolve(root, 'play', GAMES[mode], 'puzzles');
const markerName = '.pixieed-generated-puzzle-share-pages';
const markerContents = 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n';
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const maxCandidates = Math.min(1000, Math.max(1, Number(supabaseConfig.publicMapLimit) || 500));
const concurrency = 6;
const hiddenRenderer = createHiddenObjectOgpRenderer();

function usage() {
  return `Usage:
  node scripts/generate-puzzle-ogp-pages.mjs --help
  node scripts/generate-puzzle-ogp-pages.mjs --preview
  node scripts/generate-puzzle-ogp-pages.mjs --generate

--preview reads public map candidates and the public-post-puzzle endpoint, then prints planned paths without writing.
--generate builds side-by-side PNGs for spot-difference and picture/search-text PNGs for hidden-object, then replaces only the marked play/<game>/puzzles directories.
Hidden-object text uses an existing Playwright installation (PIXIEED_PLAYWRIGHT_MODULE); dependencies are never installed automatically.
Both data commands require puzzlePublicationEnabled and use the public publishable key only.`;
}

function assertRuntimeConfig() {
  if (supabaseConfig.puzzlePublicationEnabled !== true) throw new Error('Puzzle publication is disabled in data/site-config.js; no public data was requested.');
  if (!/^https:\/\/[^/?#]+\/?$/.test(String(supabaseConfig.url || '')) || !supabaseConfig.publishableKey) {
    throw new Error('Supabase public URL/key configuration is incomplete.');
  }
}

async function publicFetch(url) {
  const signal = AbortSignal.timeout(15000);
  return fetch(url, {
    method: 'GET',
    headers: { apikey: supabaseConfig.publishableKey, Accept: 'application/json' },
    cache: 'no-store',
    credentials: 'omit',
    signal,
  });
}

async function responseJson(response, label) {
  if (!response.ok) throw new Error(`${label} failed with HTTP ${response.status}.`);
  try { return await response.json(); } catch { throw new Error(`${label} returned invalid JSON.`); }
}

async function listCandidates() {
  const url = new URL(`/rest/v1/${encodeURIComponent(supabaseConfig.publicMapTable || 'post_map_points')}`, supabaseConfig.url);
  url.searchParams.set('select', 'post_id,puzzle_mode');
  url.searchParams.set('published_at', 'not.is.null');
  url.searchParams.set('puzzle_mode', 'in.(spot_difference,hidden_object)');
  url.searchParams.set('order', 'post_id.asc');
  url.searchParams.set('limit', String(maxCandidates));
  const rows = await responseJson(await publicFetch(url), 'Public map candidate query');
  if (!Array.isArray(rows)) throw new Error('Public map candidate query did not return an array.');
  if (rows.length >= maxCandidates) throw new Error(`Candidate limit (${maxCandidates}) reached; refusing to generate a partial page set.`);
  const seen = new Set();
  return rows.map((row) => {
    if (!row || typeof row.post_id !== 'string' || !uuidPattern.test(row.post_id)
        || !['spot_difference', 'hidden_object'].includes(row.puzzle_mode) || seen.has(row.post_id.toLowerCase())) {
      throw new Error('Public map candidate data is invalid or duplicated.');
    }
    seen.add(row.post_id.toLowerCase());
    return { postId: row.post_id.toLowerCase(), mode: row.puzzle_mode };
  });
}

async function fetchPublicPng(url) {
  // URLs have already passed createPuzzleSharePage's same-project/post allowlist.
  // Do not follow redirects to another host or accept unbounded source images.
  const response = await fetch(url, { method: 'GET', redirect: 'error', credentials: 'omit', signal: AbortSignal.timeout(15000) });
  if (!response.ok || response.headers.get('content-type')?.split(';')[0].trim().toLowerCase() !== 'image/png') throw new Error('Public OGP source is not an available PNG.');
  const limit = 512 * 1024;
  if (Number(response.headers.get('content-length')) > limit) throw new Error('Public OGP source is too large.');
  const reader = response.body?.getReader();
  if (!reader) throw new Error('Public OGP source has no body.');
  const parts = []; let size = 0;
  try {
    while (true) {
      const { value, done } = await reader.read(); if (done) break;
      size += value.length; if (size > limit) throw new Error('Public OGP source is too large.');
      parts.push(value);
    }
  } finally { await reader.cancel().catch(() => {}); }
  return Buffer.concat(parts, size);
}

async function readOnePublicPuzzle(candidate, generateImages) {
  const url = new URL('/functions/v1/public-post-puzzle', `${supabaseConfig.url.replace(/\/$/, '')}/`);
  url.searchParams.set('postId', candidate.postId);
  const response = await publicFetch(url);
  // A candidate can be withdrawn between listing and reading. The public reader's
  // 404 is authoritative and omits that page; transport/5xx failures abort all output.
  if (response.status === 404) return null;
  const payload = await responseJson(response, `Public puzzle ${candidate.postId}`);
  if (payload?.puzzle?.mode !== candidate.mode) throw new Error(`Public puzzle ${candidate.postId} no longer matches its map mode.`);
  const options = { postId: candidate.postId, supabaseUrl: supabaseConfig.url };
  const html = createPuzzleSharePage(payload, options);
  let artifacts = { html, images: [] };
  if (generateImages) {
    const [originalBytes, changedBytes] = await Promise.all([fetchPublicPng(payload.puzzle.originalImage.url), candidate.mode === 'spot_difference' ? fetchPublicPng(payload.puzzle.changedImage.url) : null]);
    artifacts = await buildPuzzleShareArtifacts(payload, options, { originalBytes, changedBytes, renderHidden: hiddenRenderer.render });
  }
  return {
    postId: candidate.postId,
    mode: candidate.mode,
    ...artifacts,
  };
}

async function loadAllPages(candidates, generateImages) {
  const pages = new Array(candidates.length);
  let nextIndex = 0;
  const workers = Array.from({ length: Math.min(concurrency, candidates.length) }, async () => {
    while (true) {
      const index = nextIndex++;
      if (index >= candidates.length) return;
      pages[index] = await readOnePublicPuzzle(candidates[index], generateImages);
    }
  });
  const completed = await Promise.allSettled(workers);
  const failure = completed.find(result => result.status === 'rejected');
  if (failure) throw failure.reason;
  return pages.filter(Boolean).sort((a, b) => a.postId.localeCompare(b.postId));
}

async function existingOutputState(outputDir) {
  try {
    const state = await lstat(outputDir);
    if (!state.isDirectory() || state.isSymbolicLink()) throw new Error('Output path exists but is not a regular directory.');
    const marker = await readFile(resolve(outputDir, markerName), 'utf8').catch(() => '');
    if (marker !== markerContents) throw new Error('Output directory is not marked as generated by this script; refusing to replace it.');
    return true;
  } catch (error) {
    if (error?.code === 'ENOENT') return false;
    throw error;
  }
}

async function replaceGeneratedOutput(outputDir, pages) {
  const token = `${process.pid}-${randomUUID()}`;
  const stageDir = `${outputDir}.stage-${token}`;
  const backupDir = `${outputDir}.backup-${token}`;
  let movedOld = false;
  try {
    await mkdir(stageDir, { recursive: false });
    await writeFile(resolve(stageDir, markerName), markerContents, { flag: 'wx' });
    for (const page of pages) {
      const directory = resolve(stageDir, page.postId);
      await mkdir(directory, { recursive: false });
      await writeFile(resolve(directory, 'index.html'), page.html, { flag: 'wx' });
      for (const image of page.images) await writeFile(resolve(directory, image.name), image.bytes, { flag: 'wx' });
    }
    if (await existingOutputState(outputDir)) {
      await rename(outputDir, backupDir);
      movedOld = true;
    }
    try { await rename(stageDir, outputDir); }
    catch (error) {
      if (movedOld) { await rename(backupDir, outputDir); movedOld = false; }
      throw error;
    }
    if (movedOld) { await rm(backupDir, { recursive: true, force: false }); movedOld = false; }
  } finally {
    await rm(stageDir, { recursive: true, force: true }).catch(() => {});
  }
}

const args = process.argv.slice(2);
if (args.length === 1 && args[0] === '--help') {
  console.log(usage());
} else if (args.length === 1 && ['--preview', '--generate'].includes(args[0])) {
  try {
    assertRuntimeConfig();
    const candidates = await listCandidates();
    const pages = await loadAllPages(candidates, args[0] === '--generate');
    const paths = pages.map(({ postId, mode }) => `play/${GAMES[mode]}/puzzles/${postId}/index.html`);
    if (args[0] === '--preview') {
      console.log(`Read ${candidates.length} candidate(s); ${pages.length} public share page(s) would be generated. No files written.`);
      for (const path of paths) console.log(path);
    } else {
      for (const mode of Object.keys(GAMES)) await replaceGeneratedOutput(outputDirFor(mode), pages.filter((page) => page.mode === mode));
      console.log(`Generated ${pages.length} public PiXiEED puzzle share page(s) in play/*/puzzles/.`);
      for (const path of paths) console.log(path);
    }
  } catch (error) {
    console.error(`PiXiEED puzzle OGP generation stopped: ${error instanceof Error ? error.message : 'unknown error'}`);
    process.exitCode = 1;
  } finally {
    await hiddenRenderer.close();
  }
} else {
  console.error(usage());
  process.exitCode = 2;
}
