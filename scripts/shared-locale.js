  function normalizeLocale(value) {
    return String(value || '').toLowerCase().startsWith('en') ? 'en' : 'ja';
  }

  function readLocale() {
    try {
      return normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
    } catch (_error) {
      return 'ja';
    }
  }

  function writeLocale(locale) {
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch (_error) {
      // Private browsing or a restricted storage context should not block UI.
    }
  }

  function apply(locale, persist = true) {
    const next = normalizeLocale(locale);
    if (persist) writeLocale(next);
    const copy = messages[next];
    document.documentElement.lang = next === 'en' ? 'en' : 'ja';
    document.documentElement.dataset.pixieedLocale = next;
    document.querySelectorAll('[data-i18n-key]').forEach((node) => {
      const key = node.dataset.i18nKey;
      if (copy[key] === undefined) return;
      node.textContent = copy[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      const key = node.dataset.i18nPlaceholder;
      if (copy[key] !== undefined) node.setAttribute('placeholder', copy[key]);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((node) => {
      const key = node.dataset.i18nAriaLabel;
      if (copy[key] !== undefined) node.setAttribute('aria-label', copy[key]);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((node) => {
      const key = node.dataset.i18nTitle;
      if (copy[key] !== undefined) node.textContent = copy[key];
    });
    document.querySelectorAll('[data-pixieed-locale-toggle]').forEach((button) => {
      button.textContent = copy.localeToggle;
      button.setAttribute('aria-label', copy.localeLabel);
      button.setAttribute('aria-pressed', String(next === 'en'));
      button.dataset.locale = next;
    });
    window.dispatchEvent(new CustomEvent('pixieed:locale-changed', {
      detail: { locale: next },
    }));
    return next;
  }

  function toggle() {
    return apply(readLocale() === 'ja' ? 'en' : 'ja');
  }

  function bind() {
    document.querySelectorAll('[data-pixieed-locale-toggle]').forEach((button) => {
      if (button.dataset.localeBound === 'true') return;
      button.dataset.localeBound = 'true';
      button.addEventListener('click', toggle);
    });
    apply(readLocale(), false);
  }

  window.PiXiEEDLocale = Object.freeze({
    apply,
    get: readLocale,
    toggle,
  });

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', bind, { once: true });
  } else {
    bind();
  }
