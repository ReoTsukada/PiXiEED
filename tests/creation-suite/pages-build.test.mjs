import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildPagesSite } from '../../scripts/build-pages-site.mjs';

test('Pages artifact includes tracked site and generated OGP, excludes private and untracked work', async t => {
  const scratch = await mkdtemp(join(tmpdir(), 'pixieed-pages-test-')); t.after(() => rm(scratch, { recursive: true, force: true }));
  const root = join(scratch, 'source'); await mkdir(root);
  execFileSync('git', ['init', '-q', root]);
  const entries = { 'index.html': '<h1>site</h1>', 'assets/test.bin': 'asset', 'js/site.mjs': 'export const ready = true;', 'data/site-config.js': 'export const publicConfig = true;', 'supabase/private.sql': 'private', 'tests/fixture.html': 'fixture', 'docs/notes.html': 'notes', 'books/index.html': 'prototype', 'books/room-preview.html': 'prototype room', 'assets/books/room-scene.json': '{}', 'css/books-room.css': 'canvas{}', 'js/books-room.mjs': 'export {};', 'shops/index.html': '<h1>retired route</h1>', 'stores/cafe-hoshi.html': '<h1>legacy store</h1>' };
  for (const [name, value] of Object.entries(entries)) { await mkdir(join(root, name, '..'), { recursive: true }); await writeFile(join(root, name), value); }
  execFileSync('git', ['add', '.'], { cwd: root });
  await writeFile(join(root, 'experiment.html'), 'untracked');
  const page = 'play/hidden-object/puzzles/11111111-1111-4111-8111-111111111111';
  const legacyPage = 'play/spot-difference/puzzles/pixfind-sd-22222222-2222-4222-8222-222222222222';
  await mkdir(join(root, page), { recursive: true });
  await mkdir(join(root, legacyPage), { recursive: true });
  await writeFile(join(root, 'play/hidden-object/puzzles/.pixieed-generated-puzzle-share-pages'), 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n');
  await writeFile(join(root, 'play/spot-difference/puzzles/.pixieed-generated-puzzle-share-pages'), 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n');
  await writeFile(join(root, page, 'index.html'), '<meta property="og:image">');
  await writeFile(join(root, page, 'ogp-1234567890abcdef.png'), 'PNG');
  await writeFile(join(root, legacyPage, 'index.html'), '<meta property="og:image">');
  await writeFile(join(root, legacyPage, 'ogp-fedcba0987654321.png'), 'PNG');
  const result = await buildPagesSite({ root, output: join(scratch, 'site') });
  assert.equal(result.puzzlePages, 2); assert.equal(result.files, 10);
  assert.equal(await readFile(join(result.output, 'index.html'), 'utf8'), '<h1>site</h1>');
  assert.equal(await readFile(join(result.output, 'stores/cafe-hoshi.html'), 'utf8'), '<h1>legacy store</h1>');
  assert.equal(await readFile(join(result.output, page, 'index.html'), 'utf8'), '<meta property="og:image">');
  assert.equal(await readFile(join(result.output, legacyPage, 'index.html'), 'utf8'), '<meta property="og:image">');
  for (const path of ['supabase/private.sql', 'tests/fixture.html', 'docs/notes.html', 'experiment.html', 'books/index.html', 'books/room-preview.html', 'assets/books/room-scene.json', 'css/books-room.css', 'js/books-room.mjs', 'shops/index.html']) await assert.rejects(readFile(join(result.output, path)), { code: 'ENOENT' });
  await writeFile(join(root, page, 'answers.json'), 'must not leak');
  await assert.rejects(buildPagesSite({ root, output: join(scratch, 'bad-site') }), /Unexpected generated puzzle file/);
  await rm(join(root, page, 'answers.json'));
  const badLegacy = 'play/hidden-object/puzzles/pixfind-sd-33333333-3333-4333-8333-333333333333';
  await mkdir(join(root, badLegacy));
  await writeFile(join(root, badLegacy, 'index.html'), '<meta>');
  await assert.rejects(buildPagesSite({ root, output: join(scratch, 'bad-legacy-site') }), /Unexpected generated puzzle entry/);
});

test('Pages artifact regenerates event pages and removes stale event URLs while leaving unrelated untracked work out', async t => {
  const scratch = await mkdtemp(join(tmpdir(), 'pixieed-event-pages-build-'));
  t.after(() => rm(scratch, { recursive: true, force: true }));
  const root = join(scratch, 'source'); await mkdir(root);
  execFileSync('git', ['init', '-q', root]);
  await mkdir(join(root, 'data')); await mkdir(join(root, 'events', 'removed'), {recursive:true});
  const catalog = {version:1,events:[{id:'verified-edition',name:'Verified Pixel Exhibition',description:'An independently described exhibition.',startDate:'2026-11-01',endDate:'2026-11-02',status:'upcoming',sourceUrl:'https://example.test/official',checkedAt:'2026-10-01'}]};
  await writeFile(join(root,'data/pixel-art-events.json'),JSON.stringify(catalog));
  await writeFile(join(root,'sitemap.xml'),'<?xml version="1.0"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>https://pixieed.jp/</loc></url>\n  <url><loc>https://pixieed.jp/events/removed/</loc></url>\n</urlset>\n');
  await writeFile(join(root,'events/.pixieed-generated-event-pages'),'Generated by scripts/generate-event-pages.mjs\n');
  await writeFile(join(root,'events/removed/index.html'),'obsolete');
  execFileSync('git',['add','.'],{cwd:root});
  await writeFile(join(root,'unreviewed.html'),'private experiment');
  await mkdir(join(root,'js'));
  await writeFile(join(root,'js/home-audio.mjs'),'export const audioReview = true;');
  const result=await buildPagesSite({root,output:join(scratch,'site')});
  assert.equal(result.eventPages,1);
  assert.match(await readFile(join(result.output,'events/verified-edition/index.html'),'utf8'),/Verified Pixel Exhibition/);
  assert.equal(await readFile(join(result.output,'js/home-audio.mjs'),'utf8'),'export const audioReview = true;', 'the reviewed home module is present in pre-commit builds');
  const sitemap=await readFile(join(result.output,'sitemap.xml'),'utf8');
  assert.match(sitemap,/https:\/\/pixieed.jp\/events\/verified-edition\//);
  assert.doesNotMatch(sitemap,/events\/removed/);
  await assert.rejects(readFile(join(result.output,'events/removed/index.html')),{code:'ENOENT'});
  await assert.rejects(readFile(join(result.output,'unreviewed.html')),{code:'ENOENT'});
});
