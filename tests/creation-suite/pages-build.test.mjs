test('standalone and old generated pages get local sans typography without changing content or artwork fonts', () => {
  const source = '<!doctype html><html><head><meta charset="utf-8"><link rel="canonical" href="https://pixieed.jp/example/"></head><body><h1>合成案内</h1><code style="font-family:monospace">A1</code><canvas></canvas></body></html>';
  const result = addSiteFontFallback(source);
  assert.match(result, /<style data-site-font>:root\{font-family:[^}]*"Hiragino Sans"[^}]*sans-serif\}/);
  assert.match(result, /button,input,select,textarea\{font-family:inherit\}/);
  assert.equal(result.replace(/\n<style data-site-font>[\s\S]*?<\/style>/, ''), source);
  assert.equal(addSiteFontFallback(result), result, 'an existing baseline is not duplicated');
  assert.doesNotMatch(result, /@font-face|https:\/\/(?:fonts\.|fonts\/)/);
});

test('Pages artifact includes tracked site and generated OGP, excludes private and untracked work', async t => {
  const scratch = await mkdtemp(join(tmpdir(), 'pixieed-pages-test-')); t.after(() => rm(scratch, { recursive: true, force: true }));
  const root = join(scratch, 'source'); await mkdir(root);
  execFileSync('git', ['init', '-q', root]);
  const entries = {
    'index.html': '<h1>site</h1>', 'assets/test.bin': 'asset', 'js/site.mjs': 'export const ready = true;', 'data/site-config.js': 'export const publicConfig = true;',
    'supabase/private.sql': 'private', 'tests/fixture.html': 'fixture', 'docs/notes.html': 'notes',
    'admanager-rewarded-test/index.html': '<h1>LOCAL MOCK ONLY</h1>',
    'admanager-rewarded-test/mock-adapter.mjs': 'export const mockGrant = true;',
    'admanager-rewarded-test/page.mjs': 'export const localTestPage = true;',
    'books/index.html': '<h1>catalog</h1>', 'books/room-preview.html': '<meta name="robots" content="noindex,follow">',
    'assets/books/room-products.json': '[{"id":"drawn-thumbnail","shopThumbnail":{"src":"/assets/books/thumb.png","width":32,"height":32}}]', 'assets/books/room-commerce.json': '{"associateName":"PiXiEED","enrollmentConfirmed":true}',
    'assets/books/thumb.png': 'registered thumbnail', 'assets/books/unregistered.png': 'private draft',
    'assets/books/room-scene.json': '{}', 'css/books.css': '.catalog{}', 'css/books-room.css': 'canvas{}',
    'js/books-catalog.mjs': 'export {};', 'js/books-commerce.mjs': 'export {};', 'js/books-room-catalog.mjs': 'export {};', 'js/books-room.mjs': 'export {};',
    'shops/index.html': '<h1>retired route</h1>', 'stores/cafe-hoshi.html': '<h1>legacy store</h1>'
  };
  for (const [name, value] of Object.entries(entries)) { await mkdir(join(root, name, '..'), { recursive: true }); await writeFile(join(root, name), value); }
  execFileSync('git', ['add', '.'], { cwd: root });
  await writeFile(join(root, 'experiment.html'), 'untracked');
  const page = 'play/hidden-object/puzzles/11111111-1111-4111-8111-111111111111';
  const legacyPage = 'play/spot-difference/puzzles/pixfind-sd-22222222-2222-4222-8222-222222222222';
  await mkdir(join(root, page), { recursive: true });
  await mkdir(join(root, legacyPage), { recursive: true });
  await writeFile(join(root, 'play/hidden-object/puzzles/.pixieed-generated-puzzle-share-pages'), 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n');
  await writeFile(join(root, 'play/spot-difference/puzzles/.pixieed-generated-puzzle-share-pages'), 'Generated by scripts/generate-puzzle-ogp-pages.mjs\n');
  await writeFile(join(root, page, 'index.html'), '<meta property="og:image">');
  await writeFile(join(root, page, 'ogp-1234567890abcdef.png'), 'PNG');
  await writeFile(join(root, legacyPage, 'index.html'), '<meta property="og:image">');
  await writeFile(join(root, legacyPage, 'ogp-fedcba0987654321.png'), 'PNG');
  const result = await buildPagesSite({ root, output: join(scratch, 'site') });
  assert.equal(result.puzzlePages, 2); assert.equal(result.files, 18);
  assert.equal(await readFile(join(result.output, 'index.html'), 'utf8'), '<h1>site</h1>');
  assert.equal(await readFile(join(result.output, 'books/index.html'), 'utf8'), '<h1>catalog</h1>');
  assert.equal(await readFile(join(result.output, 'assets/books/room-products.json'), 'utf8'), entries['assets/books/room-products.json']);
  assert.equal(await readFile(join(result.output, 'assets/books/thumb.png'), 'utf8'), 'registered thumbnail');
  await assert.rejects(readFile(join(result.output, 'assets/books/unregistered.png')), { code: 'ENOENT' });
  assert.equal(await readFile(join(result.output, 'assets/books/room-commerce.json'), 'utf8'), '{"associateName":"PiXiEED","enrollmentConfirmed":true}');
  for (const path of ['css/books.css', 'js/books-catalog.mjs', 'js/books-commerce.mjs', 'js/books-room-catalog.mjs']) assert.ok(await readFile(join(result.output, path), 'utf8'));
  assert.equal(await readFile(join(result.output, 'stores/cafe-hoshi.html'), 'utf8'), '<h1>legacy store</h1>');
  assert.equal(await readFile(join(result.output, page, 'index.html'), 'utf8'), '<meta property="og:image">');
  assert.equal(await readFile(join(result.output, legacyPage, 'index.html'), 'utf8'), '<meta property="og:image">');
  for (const path of ['admanager-rewarded-test/index.html', 'admanager-rewarded-test/mock-adapter.mjs', 'admanager-rewarded-test/page.mjs', 'supabase/private.sql', 'tests/fixture.html', 'docs/notes.html', 'experiment.html', 'books/room-preview.html', 'assets/books/room-scene.json', 'css/books-room.css', 'js/books-room.mjs', 'shops/index.html']) await assert.rejects(readFile(join(result.output, path)), { code: 'ENOENT' });
  await writeFile(join(root, page, 'answers.json'), 'must not leak');
  await assert.rejects(buildPagesSite({ root, output: join(scratch, 'bad-site') }), /Unexpected generated puzzle file/);
  await rm(join(root, page, 'answers.json'));
  const badLegacy = 'play/hidden-object/puzzles/pixfind-sd-33333333-3333-4333-8333-333333333333';
  await mkdir(join(root, badLegacy));
  await writeFile(join(root, badLegacy, 'index.html'), '<meta>');
  await assert.rejects(buildPagesSite({ root, output: join(scratch, 'bad-legacy-site') }), /Unexpected generated puzzle entry/);
});

