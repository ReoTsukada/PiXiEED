import test from 'node:test';
import assert from 'node:assert/strict';
import { decodeGeneratedPreview, needsDecodedOutputPreview } from '../../js/creation/conversion-preview-decoder.mjs';
import { decodeRaster, encodeRaster } from '../../js/creation/conversion-raster.mjs';

class TestFile {
  constructor(parts, name, options = {}) {
    this.parts = parts;
    this.name = name;
    this.type = options.type || '';
    this.size = parts.reduce((total, part) => total + part.size, 0);
  }
  async arrayBuffer() {
    const buffers = await Promise.all(this.parts.map(async (part) => new Uint8Array(await part.arrayBuffer())));
    const bytes = new Uint8Array(this.size);
    let offset = 0;
    for (const buffer of buffers) { bytes.set(buffer, offset); offset += buffer.length; }
    return bytes.buffer;
  }
}

function rgbaFrame(width = 2, height = 1, values = [1, 2, 3, 255, 4, 5, 6, 255]) {
  return { width, height, data: new Uint8ClampedArray(values) };
}

test('recognizes only local decoded-output formats, case-insensitively', () => {
  for (const ext of ['tif', 'tiff', 'tga', 'targa', 'qoi', 'ppm', 'pgm', 'pbm', 'pnm', 'pam']) {
    assert.equal(needsDecodedOutputPreview(`result.${ext.toUpperCase()}`), true);
  }
  for (const name of ['result.png', 'result.gif', 'result.apng', 'result.wav', 'result.mp4', 'no-extension']) {
    assert.equal(needsDecodedOutputPreview(name), false);
  }
});

test('passes exact generated bytes, filename, MIME type and signal; returns first RGBA frame with partial metadata', async () => {
  const bytes = new Uint8Array([0, 255, 12, 34]);
  const blob = new Blob([bytes], { type: 'image/x-qoi' });
  const signal = new AbortController().signal;
  const decodedFrame = rgbaFrame();
  let captured;
  const result = await decodeGeneratedPreview({ blob, filename: 'generated.QOI', signal }, {
    FileImpl: TestFile,
    async loadFile(file, options) {
      captured = { file, options, bytes: new Uint8Array(await file.arrayBuffer()) };
      return { frames: [decodedFrame, rgbaFrame()] };
    }
  });
  assert.equal(captured.file.name, 'generated.QOI');
  assert.equal(captured.file.type, 'image/x-qoi');
  assert.deepEqual(captured.bytes, bytes);
  assert.equal(captured.options.signal, signal);
  assert.deepEqual(result, { width: 2, height: 1, data: decodedFrame.data, frameCount: 2, kind: 'decoded-output', partial: true, firstPageOnly: false, note: '' });
  assert.deepEqual(bytes, new Uint8Array([0, 255, 12, 34]));
});

test('returns the complete decoded frame and labels a single-page non-TIFF result as non-partial', async () => {
  const frame = rgbaFrame(1, 1, [8, 9, 10, 255]);
  const result = await decodeGeneratedPreview({ blob: new Blob([new Uint8Array([1])]), filename: 'a.qoi' }, {
    FileImpl: TestFile,
    loadFile: async () => ({ frames: [frame] })
  });
  assert.equal(result.frameCount, 1);
  assert.equal(result.partial, false);
  assert.equal(result.firstPageOnly, false);
  assert.equal(result.note, '');
  assert.equal(result.data, frame.data);
  assert.equal(result.data.length, 4);
});

test('TIFF keeps the raster decoder first-page note and reports that later pages are unknown', async () => {
  const sample = { width: 2, height: 1, data: new Uint8ClampedArray([20, 40, 60, 255, 80, 100, 120, 255]) };
  const blob = encodeRaster(sample, 'tiff');
  const result = await decodeGeneratedPreview({ blob, filename: 'generated.tif' }, {
    FileImpl: TestFile,
    async loadFile(file) {
      const bytes = new Uint8Array(await file.arrayBuffer());
      return { frames: [decodeRaster(bytes, 'tiff')] };
    }
  });
  assert.equal(result.frameCount, 1);
  assert.equal(result.partial, true);
  assert.equal(result.firstPageOnly, true);
  assert.match(result.note, /TIFFは先頭ページを読み込みます/);
  assert.deepEqual(result.data, sample.data);
});

test('does not call the decoder for browser-native image, audio, and video formats', async () => {
  let calls = 0;
  for (const filename of ['actual.png', 'actual.gif', 'actual.apng', 'actual.mp3', 'actual.webm']) {
    assert.equal(await decodeGeneratedPreview({ blob: new Blob([new Uint8Array([1])]), filename }, {
      FileImpl: TestFile,
      loadFile: async () => { calls++; return { frames: [rgbaFrame()] }; }
    }), null);
  }
  assert.equal(calls, 0);
});

test('checks abort before and after decoding and ignores late decoded output', async () => {
  const before = new AbortController(); before.abort();
  let calls = 0;
  await assert.rejects(decodeGeneratedPreview({ blob: new Blob([new Uint8Array([1])]), filename: 'a.qoi', signal: before.signal }, {
    FileImpl: TestFile, loadFile: async () => { calls++; return { frames: [rgbaFrame()] }; }
  }), { name: 'AbortError' });
  assert.equal(calls, 0);

  const during = new AbortController();
  await assert.rejects(decodeGeneratedPreview({ blob: new Blob([new Uint8Array([1])]), filename: 'a.qoi', signal: during.signal }, {
    FileImpl: TestFile,
    async loadFile(_file, { signal }) { during.abort(); assert.equal(signal, during.signal); return { frames: [rgbaFrame()] }; }
  }), { name: 'AbortError' });
});

test('rejects missing, excessive, or malformed frame data', async (t) => {
  const invalid = [
    { frames: [] },
    { frames: Array(601).fill(rgbaFrame()) },
    { frames: [{ width: 0, height: 1, data: new Uint8Array(4) }] },
    { frames: [{ width: 4097, height: 1, data: new Uint8Array(4) }] },
    { frames: [{ width: 4096, height: 4096, data: new Uint8Array(4) }] },
    { frames: [{ width: 1, height: 1, data: new Uint16Array(2) }] },
    { frames: [{ width: 1, height: 1, data: new Uint8Array(3) }] }
  ];
  for (const value of invalid) {
    await t.test(String(invalid.indexOf(value)), async () => {
      await assert.rejects(decodeGeneratedPreview({ blob: new Blob([new Uint8Array([1])]), filename: 'a.pam' }, {
        FileImpl: TestFile, loadFile: async () => value
      }), RangeError);
    });
  }
});
